create policy "students visible by role" on public."students"
for select using (
  public.is_admin()
  or public.current_role() = 'teacher'
  or "profile_id" = auth.uid()
);
create policy "admin students all" on public."students" for all using (public.is_admin()) with check (public.is_admin());

create policy "teachers visible by role" on public."teachers"
for select using (
  public.is_admin()
  or public.current_role() = 'student'
  or "profile_id" = auth.uid()
);
create policy "admin teachers all" on public."teachers" for all using (public.is_admin()) with check (public.is_admin());

create policy "teacher subjects visible" on public."teacher_subjects"
for select using (
  public.is_admin()
  or "TeacherID" = public.current_teacher_id()
);
create policy "admin teacher subjects all" on public."teacher_subjects" for all using (public.is_admin()) with check (public.is_admin());

create policy "success rate visible" on public."success_rate"
for select using (
  public.is_admin()
  or "TeacherID" = public.current_teacher_id()
  or "StudentID" = public.current_student_id()
);

create policy "admin success rate all" on public."success_rate"
for all using (public.is_admin()) with check (public.is_admin());

create policy "teacher success rate insert" on public."success_rate"
for insert with check (
  "TeacherID" = public.current_teacher_id()
  and exists (
    select 1 from public."teacher_subjects" ts
    where ts."TeacherID" = public.current_teacher_id()
      and ts."SubjectID" = "SubjectID"
      and ts."CanEditGrades" = true
  )
);

create policy "teacher success rate update" on public."success_rate"
for update using (
  "TeacherID" = public.current_teacher_id()
  and exists (
    select 1 from public."teacher_subjects" ts
    where ts."TeacherID" = public.current_teacher_id()
      and ts."SubjectID" = "SubjectID"
      and ts."CanEditGrades" = true
  )
) with check (
  "TeacherID" = public.current_teacher_id()
);
